from __future__ import annotations

import json
import tempfile
from pathlib import Path

from engine.canon import DEFAULT_CANON, index_canon
from engine.db import connect, init_db, reset_db
from engine.model_gateway import (
    apply_model_request,
    bridge_play,
    create_decision_request,
    export_request,
    import_response,
    model_status,
    pending_requests,
    set_model_config,
)
from engine.simulation import seed_demo


def run():
    reset_db()
    init_db()
    seed_demo()
    index_canon(DEFAULT_CANON)

    with connect() as conn:
        cfg = set_model_config(
            conn,
            action_provider="manual_chatgpt",
            decision_provider="rules",
            narrator_provider="manual_chatgpt",
        )
        assert cfg["action_provider"] == "manual_chatgpt"
        assert cfg["narrator_provider"] == "manual_chatgpt"

        # A deterministic action should resolve state first and queue only narration.
        result = bridge_play(conn, "I wait here for 2 days.", "chatgpt")
        assert result["status"] == "awaiting_narration"
        assert result["turn"]["day_ended"] == 2
        nreq = result["next_request"]
        assert nreq["task_type"] == "narration"
        assert "ChatGPT Bridge Request" in Path(nreq["packet_path"]).read_text(encoding="utf-8")

        narr_response = json.dumps({
            "task_type": "narration",
            "request_id": nreq["request_id"],
            "narration": "The road carries on around the wanderer while two quiet days pass."
        })
        import_response(conn, nreq["request_id"], narr_response)
        applied = apply_model_request(conn, nreq["request_id"])
        assert applied["status"] == "applied"
        turn = conn.execute("SELECT narration_text FROM turns WHERE id=?", (applied["turn_id"],)).fetchone()
        assert "two quiet days" in turn[0]

        # Unknown intent queues interpretation and does not advance the world merely because a model is needed.
        day_before = conn.execute("SELECT current_day FROM world_state WHERE id=1").fetchone()[0]
        ares = bridge_play(conn, "I make a complicated bargain involving the room, the merchant and a future favor.", "claude")
        assert ares["status"] == "awaiting_action_interpretation"
        assert conn.execute("SELECT current_day FROM world_state WHERE id=1").fetchone()[0] == day_before
        assert "Claude Bridge Request" in Path(ares["packet_path"]).read_text(encoding="utf-8")

        # Unsupported bargains must not silently become observation.
        response = f'''```json
{{
  "task_type": "action_interpretation",
  "request_id": {ares['request_id']},
  "proposal": {{
    "action_type": "observe",
    "confidence": 0.61,
    "target_actor_name": null,
    "target_location_name": null,
    "interaction_id": null,
    "response_choice": null,
    "duration_days": 0,
    "purpose": "Take stock before attempting a complicated bargain",
    "needs_interpretation": false,
    "note": "The original bargain cannot be safely encoded by the current action vocabulary."
  }},
  "reasoning_summary": "Use the closest non-mutating supported action."
}}
```'''
        import_response(conn, ares["request_id"], response)
        applied_action = apply_model_request(conn, ares["request_id"])
        assert applied_action["status"] == "not_applied"
        assert "cannot be replaced" in applied_action["summary"]

        # The same pending request can be exported for the other web-chat model without changing engine semantics.
        cross_path = export_request(conn, ares["request_id"], provider="chatgpt")
        cross_text = Path(cross_path).read_text(encoding="utf-8")
        assert "ChatGPT Bridge Request" in cross_text

        # Queue and apply one bounded NPC decision manually. The model chooses only among
        # concrete candidates generated by DEC-01; it cannot invent an abstract goal-progress action.
        actor = conn.execute("SELECT id FROM actors WHERE name='[DEMO] House of Seven Ledgers'").fetchone()
        dreq = create_decision_request(conn, int(actor[0]), "STRATEGIC", "claude")
        dctx = json.loads(conn.execute("SELECT input_json FROM model_requests WHERE id=?", (dreq["request_id"],)).fetchone()[0])
        assert dctx["actor_context"]["canon"] == []
        assert dctx["candidate_options"]
        chosen_key=dctx["candidate_options"][0]["candidate_key"]
        dresponse = json.dumps({
            "task_type": "npc_decision",
            "request_id": dreq["request_id"],
            "proposal": {
                "candidate_key": chosen_key,
                "rationale": "Choose one engine-supplied feasible candidate from the actor-safe envelope."
            },
            "reasoning_summary": "No new world facts or targets are invented."
        })
        import_response(conn, dreq["request_id"], dresponse)
        dapplied = apply_model_request(conn, dreq["request_id"])
        assert dapplied["status"] == "applied"
        assert conn.execute("SELECT COUNT(*) FROM decisions WHERE id=?", (dapplied["decision_id"],)).fetchone()[0] == 1
        assert conn.execute("SELECT COUNT(*) FROM decision_evaluations WHERE decision_id=?",(dapplied["decision_id"],)).fetchone()[0] == 1

        assert model_status(conn)["request_counts"].get("applied", 0) >= 2
        assert model_status(conn)["request_counts"].get("error", 0) == 1
        conn.commit()

    print("model_gateway_test: PASS")


if __name__ == "__main__":
    run()
